import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
const chosen=process.argv.find(value=>value.startsWith('--runtime='))?.slice(10);
const {buildRuntimeImports,createRuntimeFilesystem,inspectRuntimeWasmLayout}=await import(chosen?pathToFileURL(path.resolve(chosen)).href:new URL('./compiler_runtime.mjs',import.meta.url).href);
import {observeAllocations} from './allocation_probe.mjs';
const bytes=await fs.readFile(process.argv[2]);
const runtime=buildRuntimeImports([],createRuntimeFilesystem(),inspectRuntimeWasmLayout(bytes));
const allocations=process.argv.includes('--observe')?observeAllocations(runtime,64*1024*1024):undefined,samples=[];
const holes=Number(process.argv.find(value=>value.startsWith('--holes='))?.slice(8)??0);
assert(Number.isSafeInteger(holes)&&holes>=0);
const retained=Array.from({length:holes*2},()=>runtime.env.malloc(16));
for(let index=1;index<retained.length;index+=2) runtime.env.free(retained[index]);
let start,built,index;
runtime.env.begin_save_sample=s=>{index=Number(s);start=performance.now();};
runtime.env.snapshot_finished=()=>{built=performance.now();};
runtime.env.serialization_finished=length=>{if(index>0) samples.push({snapshotMs:built-start,serializeMs:performance.now()-built,bytes:Number(length)});};
const {instance}=await WebAssembly.instantiate(bytes,runtime);assert.equal(instance.exports.main(),0);
for(let index=0;index<retained.length;index+=2) runtime.env.free(retained[index]);
if(allocations) assert.equal(allocations.live,0);
const summary=field=>{const data=samples.map(s=>s[field]).sort((a,b)=>a-b);return {medianMs:data[12],p95Ms:data[23],maxMs:data.at(-1)};};
console.log(JSON.stringify({holes,snapshot:summary('snapshotMs'),serialize:summary('serializeMs'),bytes:samples[0].bytes,...(allocations?{peakBytes:allocations.peak}:{})},null,2));
